/* =========================================
   Detect Language
   ========================================= */

function detectLanguage() {

    const saved =
        localStorage.getItem("hyprix-language");

    if (saved && translations[saved]) {
        return saved;
    }

    const browser =
        navigator.language || "en";

    const language =
        browser.toLowerCase().split("-")[0];

    return translations[language]
        ? language
        : "en";
}


/* =========================================
   Translate Page
   ========================================= */

function translatePage(language) {

    const t = translations[language];

    if (!t) return;

    document.documentElement.lang = language;


    /* NAVIGATION */

    document.querySelector(
        'nav a[href="#home"]'
    ).textContent = t.home;

    document.querySelector(
        'nav a[href="#apps"]'
    ).textContent = t.apps;

    document.querySelector(
        'nav a[href="#games"]'
    ).textContent = t.games;

    document.querySelector(
        'nav a[href="#about"]'
    ).textContent = t.about;


    /* HERO */

    document.querySelector(
        ".badge"
    ).textContent = t.badge;

    document.querySelector(
        ".hero h1"
    ).innerHTML =
        `${t.hero1}<br>${t.hero2}<br><span>${t.hero3}</span>`;

    document.querySelector(
        ".hero p"
    ).textContent = t.heroText;

    document.querySelector(
        ".hero .button"
    ).textContent = t.explore;


    /* APPS HEADER */

    document.querySelector(
        "#apps .section-label"
    ).textContent = t.whatWeMake;

    document.querySelector(
        "#apps h2"
    ).textContent = t.ourApps;


    /* APP CARDS */

    const appCards =
        document.querySelectorAll("#apps .cards > .card");


    /*
       CARD 1 = WEATHER
    */

    if (appCards[0]) {

        const weather =
            appCards[0];

        weather.querySelector(
            ".status"
        ).textContent = t.availableNow;

        weather.querySelector(
            "h3"
        ).textContent = t.weather;

        weather.querySelector(
            "p"
        ).textContent = t.weatherDescription;

        weather.querySelector(
            ".download-button"
        ).textContent = t.download;
    }


    /*
       CARD 2 = CALCULATOR
    */

    if (appCards[1]) {

        const calculator =
            appCards[1];

        calculator.querySelector(
            ".status"
        ).textContent = t.availableNow;

        calculator.querySelector(
            "h3"
        ).textContent = t.calculator;

        calculator.querySelector(
            "p"
        ).textContent = t.calculatorDescription;

        calculator.querySelector(
            ".download-button"
        ).textContent = t.download;
    }


    /*
       CARD 3 = MORE APPS
    */

    if (appCards[2]) {

        const moreApps =
            appCards[2];

        moreApps.querySelector(
            "h3"
        ).textContent = t.moreApps;

        moreApps.querySelector(
            "p"
        ).textContent = t.moreAppsDescription;

        moreApps.querySelector(
            ".status"
        ).textContent = t.inDevelopment;
    }


    /* GAMES */

    document.querySelector(
        "#games .section-label"
    ).textContent = t.playSomething;

    document.querySelector(
        "#games h2"
    ).textContent = t.ourGames;

    document.querySelector(
        ".game-box .status"
    ).textContent = t.comingSoon;

    document.querySelector(
        ".game-box h3"
    ).textContent = t.gamesTitle;

    document.querySelector(
        ".game-box p"
    ).textContent = t.gamesDescription;


    /* ABOUT */

    document.querySelector(
        "#about .section-label"
    ).textContent = t.aboutHyprix;

    document.querySelector(
        "#about h2"
    ).innerHTML =
        `${t.aboutTitle}<br><span>${t.aboutTitle2}</span>`;

    document.querySelector(
        "#about > p:last-child"
    ).textContent = t.aboutDescription;
}


/* =========================================
   Language Button
   ========================================= */

function createLanguageButton() {

    const container =
        document.createElement("div");

    container.id =
        "language-container";

    container.innerHTML = `
        <button
            id="language-button"
            type="button"
            aria-label="Choose language"
        >
            🌐 Language
        </button>

        <div id="language-menu">

            <button data-language="en">
                🇺🇸 English
            </button>

            <button data-language="es">
                🇪🇸 Español
            </button>

            <button data-language="fr">
                🇫🇷 Français
            </button>

            <button data-language="de">
                🇩🇪 Deutsch
            </button>

            <button data-language="pt">
                🇵🇹 Português
            </button>

            <button data-language="it">
                🇮🇹 Italiano
            </button>

            <button data-language="ja">
                🇯🇵 日本語
            </button>

            <button data-language="ko">
                🇰🇷 한국어
            </button>

            <button data-language="zh">
                🇨🇳 中文
            </button>

            <button data-language="ru">
                🇷🇺 Русский
            </button>

        </div>
    `;


    document
        .querySelector("header")
        .appendChild(container);


    const button =
        document.getElementById(
            "language-button"
        );

    const menu =
        document.getElementById(
            "language-menu"
        );


    button.addEventListener(
        "click",
        function () {

            menu.classList.toggle(
                "open"
            );

        }
    );


    menu
        .querySelectorAll("button")
        .forEach(function (item) {

            item.addEventListener(
                "click",
                function () {

                    const language =
                        this.dataset.language;

                    localStorage.setItem(
                        "hyprix-language",
                        language
                    );

                    translatePage(
                        language
                    );

                    menu.classList.remove(
                        "open"
                    );

                }
            );

        });


    document.addEventListener(
        "click",
        function (event) {

            if (
                !container.contains(
                    event.target
                )
            ) {

                menu.classList.remove(
                    "open"
                );

            }

        }
    );
}


/* =========================================
   Start
   ========================================= */

document.addEventListener(
    "DOMContentLoaded",
    function () {

        createLanguageButton();

        translatePage(
            detectLanguage()
        );

    }
);
